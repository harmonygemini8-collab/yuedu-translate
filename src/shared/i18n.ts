export const CATALOGS: Record<UiLang, Catalog> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en, ja, vi, ms, ar };

export const RTL_LANGUAGES = new Set<string>(['ar']);

export const isUiLangSetting = (value: unknown): value is UiLangSetting =>
  value === 'auto' || (typeof value === 'string' && Object.hasOwn(UI_LANGUAGES, value));

/** Map a browser locale (e.g. "zh-HK", "vi-VN", "en-US") to a supported UI language. */
export function resolveUiLang(setting: UiLangSetting, browserLang: string = globalThis.navigator?.language ?? 'en'): UiLang {
  if (setting !== 'auto') return setting;
  const lang = browserLang.toLowerCase();
  if (lang.startsWith('zh')) return /-(tw|hk|mo|hant)/.test(lang) ? 'zh-TW' : 'zh-CN';
  for (const code of ['ja', 'vi', 'ms', 'ar', 'en'] as const) if (lang === code || lang.startsWith(`${code}-`)) return code;
  return 'en';
}

export type Translator = (key: MessageKey, params?: Record<string, string | number>) => string;

export function createTranslator(lang: UiLang): Translator {
  const catalog = CATALOGS[lang];
  return (key, params) => {
    const text = catalog[key] ?? zhCN[key];
    return params ? text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match)) : text;
  };
}

/**
 * Localise static extension pages: elements carry data-i18n="key" (text) and
 * data-i18n-attr="attr:key" (attributes). Also sets the page language and direction.
 */
export function applyTranslations(doc: Document, lang: UiLang, t: Translator = createTranslator(lang)): void {
  doc.documentElement.lang = lang;
  doc.documentElement.dir = RTL_LANGUAGES.has(lang) ? 'rtl' : 'ltr';
  doc.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as MessageKey);
  });
  doc.querySelectorAll<HTMLElement>('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr!.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim() as MessageKey));
    }
  });
}
